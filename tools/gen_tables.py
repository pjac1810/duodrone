"""Generate src/tables.h: the integer tables DUODRONE's DSP uses (the FM-1 has no FPU).

  python3 tools/gen_tables.py

PITCH_TAB[c]  phase step per frame (2^32 = one cycle) of MIDI note 120 + c/100, c = 0..1199
FILT_G[i]     TPT one-pole coefficient G = g / (1 + g), g = tan(pi fc / fs), Q16, cutoff index i = 0..1023
              (fc from 20 Hz to 16 kHz, exponential)
"""

import math
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parents[1] / "src" / "tables.h"


def pitch_tab():
  out = []
  for c in range(1200):
    f = 440.0 * 2 ** ((120 + c / 100 - 69) / 12)
    out.append(round(f / FS * 2**32))
  return out


def filt_g():
  out = []
  lo, hi = 20.0, 16000.0
  for i in range(1024):
    fc = lo * (hi / lo) ** (i / 1023)
    g = math.tan(math.pi * fc / FS)
    out.append(round(g / (1 + g) * 65536))
  return out


def emit(name, ctype, vals, per=8):
  rows = []
  for i in range(0, len(vals), per):
    rows.append("  " + ", ".join(f"{v}u" for v in vals[i : i + per]) + ",")
  return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
  s = "/* SPDX-License-Identifier: GPL-3.0-only */\n/* generated by tools/gen_tables.py: do not edit */\n"
  s += "#ifndef DUODRONE_TABLES_H\n#define DUODRONE_TABLES_H\n#include <stdint.h>\n\n"
  s += emit("PITCH_TAB", "uint32_t", pitch_tab())
  s += "\n" + emit("FILT_G", "uint16_t", filt_g(), 16)
  s += "\n#endif\n"
  OUT.write_text(s)
  print(f"wrote {OUT}")


if __name__ == "__main__":
  main()
